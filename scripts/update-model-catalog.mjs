import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { gunzipSync, gzipSync } from "node:zlib";
import { MODEL_SDKS } from "../src/types.ts";
import { publicJson } from "./public-json.mjs";
import { analyzeSdkCoverage, sdkCoverageFailures } from "./sdk-coverage.mjs";

const source = "https://models.dev/api.json";
const destination = resolve("src/data/models-dev-api.ts");
const check = process.argv.slice(2).includes("--check");
if (process.argv.length > 3 || (process.argv[2] && !check)) throw new Error("Usage: node scripts/update-model-catalog.mjs [--check]");
const rawCatalog = await publicJson(source);
if (!rawCatalog || typeof rawCatalog !== "object" || Array.isArray(rawCatalog) || Object.keys(rawCatalog).length < 100) {
  throw new Error("Models.dev returned an unexpectedly small or invalid catalog");
}
const rawCoverage = analyzeSdkCoverage(rawCatalog, MODEL_SDKS);
const pick = (source, keys) => Object.fromEntries(keys.flatMap((key) => source?.[key] === undefined ? [] : [[key, source[key]]]));
const catalog = Object.fromEntries(Object.entries(rawCatalog).map(([providerId, provider]) => [providerId, {
  ...pick(provider, ["id", "name", "api", "npm", "env", "doc"]),
  models: Object.fromEntries(Object.entries(provider?.models ?? {}).map(([modelId, model]) => [modelId,
    pick(model, ["id", "name", "family", "canonical_model_id", "provider", "tool_call", "modalities", "reasoning", "reasoning_options", "limit"]),
  ])),
}]));
const coverage = analyzeSdkCoverage(catalog, MODEL_SDKS);
const failures = sdkCoverageFailures(coverage);
if (failures.length) throw new Error(failures.join("; "));
if (coverage.providers < 100 || coverage.models < 1_000 || !catalog.openai?.models || !Object.keys(catalog.openai.models).length) {
  throw new Error(`Models.dev snapshot failed completeness checks (${coverage.providers} providers, ${coverage.models} models)`);
}
if (JSON.stringify(coverage.catalogSdks) !== JSON.stringify(rawCoverage.catalogSdks)
  || JSON.stringify(coverage.modelOverrides) !== JSON.stringify(rawCoverage.modelOverrides)) {
  throw new Error("Models.dev snapshot pruning changed SDK or model routing metadata");
}
await mkdir(dirname(destination), { recursive: true });
const json = JSON.stringify(catalog);
const compressed = gzipSync(json, { level: 9 });
if (gunzipSync(compressed).toString("utf8") !== json) throw new Error("Models.dev snapshot compression round-trip failed");
const metadata = { source, fetchedAt: new Date().toISOString(), sha256: createHash("sha256").update(json).digest("hex"),
  providers: coverage.providers, models: coverage.models };
if (check) {
  const current = await readFile(destination, "utf8");
  const currentHash = current.match(/"sha256":"([a-f0-9]{64})"/)?.[1];
  if (currentHash !== metadata.sha256) throw new Error("Bundled Models.dev catalog is stale; run npm run catalog:update");
  console.log(`Bundled Models.dev catalog is current (${coverage.providers} providers, ${coverage.models} models)`);
  process.exit(0);
}
const temporary = `${destination}.${process.pid}.tmp`;
await writeFile(temporary, `// Generated by npm run catalog:update; do not edit.\nexport const metadata = ${JSON.stringify(metadata)} as const;\nexport default ${JSON.stringify(compressed.toString("base64"))};\n`);
try { await rename(temporary, destination); } finally { await rm(temporary, { force: true }); }
const models = Object.values(catalog).reduce((count, provider) => count + Object.keys(provider?.models ?? {}).length, 0);
console.log(`Saved ${Object.keys(catalog).length} providers and ${models} models to ${destination}`);
